"""Renders the Drood 2.0 designer icon: the drood under its ram-air canopy with a red "2.0".

Usage: python3 Tools/make_drood2_icon.py
Reads Tools/Drood2IconSource.png (transparent background, no text) and writes
Assets/Scripts/Core/Drood2Icon.cs (the PNG embedded as base64) plus Tools/Drood2Icon.png for
previewing. The game shows part icons at 100x100.
"""
import base64
import io
import os
from PIL import Image, ImageDraw, ImageEnhance, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "Tools", "Drood2IconSource.png")
FONT = "/System/Library/Fonts/Supplemental/Arial Rounded Bold.ttf"
SIZE = 100
SUPERSAMPLE = 4
MARGIN = 1
TEXT = "2.0"
TEXT_SIZE = 30
RED = (220, 30, 30, 255)
# The art brightened (the canopy and drood read better on the designer's dark background).
BRIGHTNESS = 1.56
OUTLINE = (255, 255, 255, 255)

# The art, cropped to its content and fitted into the icon (drawn large, then scaled down).
art = Image.open(SOURCE).convert("RGBA")
art = art.crop(art.getbbox())
alpha = art.getchannel("A")
art = ImageEnhance.Brightness(art.convert("RGB")).enhance(BRIGHTNESS).convert("RGBA")
art.putalpha(alpha)
big = SIZE * SUPERSAMPLE
room = big - 2 * MARGIN * SUPERSAMPLE
scale = min(room / art.width, room / art.height)
art = art.resize((round(art.width * scale), round(art.height * scale)), Image.LANCZOS)
canvas = Image.new("RGBA", (big, big), (0, 0, 0, 0))
canvas.alpha_composite(art, (MARGIN * SUPERSAMPLE, MARGIN * SUPERSAMPLE))
icon = canvas.resize((SIZE, SIZE), Image.LANCZOS)

# Red "2.0" in the bottom right corner, with a white edge so it reads on any background.
draw = ImageDraw.Draw(icon)
font = ImageFont.truetype(FONT, TEXT_SIZE)
left, top, right, bottom = draw.textbbox((0, 0), TEXT, font=font, stroke_width=2)
x = SIZE - (right - left) - 2 - left
y = SIZE - (bottom - top) - 2 - top
draw.text((x, y), TEXT, font=font, fill=RED, stroke_width=2, stroke_fill=OUTLINE)

buffer = io.BytesIO()
icon.save(buffer, "PNG", optimize=True)
png = buffer.getvalue()
with open(os.path.join(ROOT, "Tools", "Drood2Icon.png"), "wb") as f:
    f.write(png)

encoded = base64.b64encode(png).decode("ascii")
lines = "\n".join(f'            "{encoded[i:i + 100]}" +' for i in range(0, len(encoded), 100)).rstrip(" +")
with open(os.path.join(ROOT, "Assets", "Scripts", "Core", "Drood2Icon.cs"), "w") as f:
    f.write(f"""// Generated by Tools/make_drood2_icon.py. Do not edit by hand.
namespace Drood2
{{
    public static class Drood2Icon
    {{
        /// <summary>The Drood 2.0 designer icon (the drood under its ram-air canopy + red "2.0"), PNG as base64.</summary>
        public const string PngBase64 =
{lines};
    }}
}}
""")
print(f"{len(png)} bytes")
